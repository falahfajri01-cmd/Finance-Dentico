/**
 * Bundles every Supabase SQL file into ONE paste-ready script.
 *
 *   node scripts/build-install-sql.mjs
 *
 * Output: supabase/install.sql
 * Run that single file in Supabase → SQL Editor → New query → Run.
 * It is idempotent: every statement uses `create … if not exists`,
 * `drop … if exists`, or `on conflict`, so re-running is safe.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const DIR = path.join(ROOT, "supabase");

/** Order matters: schema first, then data in dependency order. */
const STEPS = [
  { file: "schema.sql", title: "SCHEMA — tables, indexes, triggers, RLS" },
  { file: "seed.sql", title: "SEED — coa_accounts (chart of accounts)" },
  { file: "seed_finance.sql", title: "SEED — finance_monthly + finance_overview_meta" },
  { file: "seed_journals.sql", title: "SEED — journals + journal_lines" },
  { file: "seed_ledger.sql", title: "SEED — gl_supplements" },
  { file: "seed_pnl.sql", title: "SEED — pnl_account_postings" },
];

const VERIFY = `
-- ═══════════════════════════════════════════════════════════════════
-- VERIFICATION — every row count must be greater than zero.
-- ═══════════════════════════════════════════════════════════════════
select 'coa_accounts'            as object, count(*) as rows from public.coa_accounts
union all select 'finance_monthly',        count(*) from public.finance_monthly
union all select 'finance_overview_meta',  count(*) from public.finance_overview_meta
union all select 'journals',               count(*) from public.journals
union all select 'journal_lines',          count(*) from public.journal_lines
union all select 'gl_supplements',         count(*) from public.gl_supplements
union all select 'pnl_account_postings',   count(*) from public.pnl_account_postings
union all select 'gl_account_movements',   count(*) from public.gl_account_movements
order by 1;
`;

const missing = STEPS.filter((s) => !fs.existsSync(path.join(DIR, s.file)));
if (missing.length) {
  console.error(
    `✖ Missing: ${missing.map((m) => m.file).join(", ")}\n  Run the generate-*-seed-sql.mjs scripts first.`
  );
  process.exit(1);
}

const banner = (n, total, title) =>
  [
    "",
    "-- " + "═".repeat(66),
    `-- [${n}/${total}] ${title}`,
    `-- source: supabase/${STEPS[n - 1].file}`,
    "-- " + "═".repeat(66),
  ].join("\n");

const parts = [
  `-- ═══════════════════════════════════════════════════════════════════`,
  `-- Dentico Finance — complete Supabase installation`,
  `-- AUTO-GENERATED by scripts/build-install-sql.mjs — do not edit by hand.`,
  `--`,
  `-- Supabase Dashboard → SQL Editor → New query → paste → Run.`,
  `-- Safe to run more than once (all statements are idempotent).`,
  `--`,
  `-- Objects created:`,
  ...STEPS.map((s) => `--   • ${s.title}`),
  `-- ═══════════════════════════════════════════════════════════════════`,
];

STEPS.forEach((step, i) => {
  const body = fs.readFileSync(path.join(DIR, step.file), "utf8").trimEnd();
  parts.push(banner(i + 1, STEPS.length, step.title), body);
});

parts.push(VERIFY.trimEnd(), "");

const outFile = path.join(DIR, "install.sql");
fs.writeFileSync(outFile, parts.join("\n"), "utf8");

const kb = (fs.statSync(outFile).size / 1024).toFixed(1);
console.log(`✔ supabase/install.sql written (${STEPS.length} sections, ${kb} KB)`);
