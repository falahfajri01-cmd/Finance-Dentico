/**
 * Generates supabase/seed_finance.sql from src/data/finance.seed.json
 * Run: node scripts/generate-finance-seed-sql.mjs
 */
import fs from "node:fs";

const seed = JSON.parse(fs.readFileSync("src/data/finance.seed.json", "utf8"));
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

const monthRows = seed.monthly.map(
  (m) => `  (${q(m.id)}, ${q(m.label)}, ${q(m.labelLong)}, ${m.revenue}, ${m.hpp}, ${m.opex}, ${m.netProfit})`
);

const payload = JSON.stringify(seed.meta).replace(/'/g, "''");

const sql = `-- AUTO-GENERATED by scripts/generate-finance-seed-sql.mjs — do not edit by hand.
-- Seeds the executive finance overview snapshots (${seed.monthly.length} months + 1 meta row).

insert into public.finance_monthly (id, month_label, month_label_long, revenue, hpp, opex, net_profit)
values
${monthRows.join(",\n")}
on conflict (id) do update set
  month_label = excluded.month_label,
  month_label_long = excluded.month_label_long,
  revenue = excluded.revenue,
  hpp = excluded.hpp,
  opex = excluded.opex,
  net_profit = excluded.net_profit;

insert into public.finance_overview_meta (id, payload)
values (true, '${payload}'::jsonb)
on conflict (id) do update set payload = excluded.payload;
`;

fs.mkdirSync("supabase", { recursive: true });
fs.writeFileSync("supabase/seed_finance.sql", sql);
console.log(`✔ supabase/seed_finance.sql written (${seed.monthly.length} months + meta)`);
