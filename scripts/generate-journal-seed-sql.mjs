/**
 * Generates supabase/seed_journals.sql from src/data/journal.seed.json
 * Run: node scripts/generate-journal-seed-sql.mjs
 */
import fs from "node:fs";

const seed = JSON.parse(fs.readFileSync("src/data/journal.seed.json", "utf8"));
const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

const journalRows = seed.map(
  (j) =>
    `  (${q(j.number)}, ${q(j.date)}, ${q(j.type)}, ${q(j.brand)}, ${q(j.branch)}, ${q(j.reference)}, ${q(j.description)}, ${j.total}, ${q(j.status)}, ${q(j.operatorName)}, ${q(j.operatorRole)}, ${q(j.operatorInitials)})`
);

const lineRows = [];
for (const j of seed) {
  j.lines.forEach((l, i) => {
    lineRows.push(
      `  ((select id from public.journals where number = ${q(j.number)}), ${i + 1}, ${q(l.accountCode)}, ${q(l.accountName)}, ${q(l.memo)}, ${l.debit}, ${l.credit})`
    );
  });
}

const sql = `-- AUTO-GENERATED by scripts/generate-journal-seed-sql.mjs — do not edit by hand.
-- Seeds journals + journal_lines (${seed.length} journals, ${lineRows.length} lines).

insert into public.journals
  (number, date, journal_type, brand, branch, reference, description, total, status, operator_name, operator_role, operator_initials)
values
${journalRows.join(",\n")}
on conflict (number) do nothing;

insert into public.journal_lines
  (journal_id, line_no, account_code, account_name, memo, debit, credit)
values
${lineRows.join(",\n")}
on conflict (journal_id, line_no) do update set
  account_code = excluded.account_code,
  account_name = excluded.account_name,
  memo         = excluded.memo,
  debit        = excluded.debit,
  credit       = excluded.credit;
`;

fs.mkdirSync("supabase", { recursive: true });
fs.writeFileSync("supabase/seed_journals.sql", sql);
console.log(`✔ supabase/seed_journals.sql written (${seed.length} journals, ${lineRows.length} lines)`);
