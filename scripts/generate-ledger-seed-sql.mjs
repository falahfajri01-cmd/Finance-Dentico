/**
 * Generates supabase/seed_ledger.sql from src/data/ledger.seed.json
 * Run: node scripts/generate-ledger-seed-sql.mjs
 */
import fs from "node:fs";

const seed = JSON.parse(fs.readFileSync("src/data/ledger.seed.json", "utf8"));
const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

const rows = seed.supplements.map(
  (s) =>
    `  (${q(s.id)}, ${q(s.accountCode)}, ${q(s.date)}, ${q(s.time)}, ${q(s.voucher)}, ${q(s.ref)}, ${q(s.branch)}, ${q(s.dot)}, ${q(s.description)}, ${q(s.subDescription ?? null)}, ${q(s.offsetLabel)}, ${s.debit}, ${s.credit}, ${q(s.bukti)}, ${q(s.memo ?? null)})`
);

const sql = `-- AUTO-GENERATED by scripts/generate-ledger-seed-sql.mjs — do not edit by hand.
-- Integrity-verified GL supplement postings (${seed.supplements.length} rows).

insert into public.gl_supplements
  (ref_id, account_code, date, time, voucher, ref, branch, dot, description, sub_desc, offset_label, debit, credit, bukti, memo)
values
${rows.join(",\n")}
on conflict (ref_id) do nothing;
`;

fs.mkdirSync("supabase", { recursive: true });
fs.writeFileSync("supabase/seed_ledger.sql", sql);
console.log(`✔ supabase/seed_ledger.sql written (${seed.supplements.length} supplement rows)`);
