/**
 * Generates supabase/seed_pnl.sql from src/data/pnl.seed.json
 * Run: node scripts/generate-pnl-seed-sql.mjs
 */
import fs from "node:fs";

const seed = JSON.parse(fs.readFileSync("src/data/pnl.seed.json", "utf8"));
const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

const rows = [];
for (const it of seed.items) {
  for (const [period, amount] of Object.entries(it.amounts)) {
    rows.push(`  (${it.seq}, ${q(it.code)}, ${q(period)}, ${amount}, ${q(it.tag ?? null)})`);
  }
}

const sql = `-- AUTO-GENERATED by scripts/generate-pnl-seed-sql.mjs — do not edit by hand.
-- Aggregated P&L postings: ${seed.items.length} accounts × ${Object.keys(seed.items[0].amounts).length} periods.

insert into public.pnl_account_postings (seq, code, period, amount, tag)
values
${rows.join(",\n")}
on conflict (code, period) do update set
  seq    = excluded.seq,
  amount = excluded.amount,
  tag    = excluded.tag;
`;

fs.mkdirSync("supabase", { recursive: true });
fs.writeFileSync("supabase/seed_pnl.sql", sql);
console.log(`✔ supabase/seed_pnl.sql written (${rows.length} posting rows)`);
