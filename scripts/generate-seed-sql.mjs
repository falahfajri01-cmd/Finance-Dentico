/**
 * Generates supabase/seed.sql from src/data/coa.seed.json
 * so the SQL seed and the frontend dummy data never diverge.
 * Run: node scripts/generate-seed-sql.mjs
 */
import fs from "node:fs";

const seed = JSON.parse(fs.readFileSync("src/data/coa.seed.json", "utf8"));
const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

const rows = seed.map(
  (a) =>
    `  (${q(a.code)}, ${q(a.name)}, ${q(a.typeLabel)}, ${q(a.group)}, ${q(a.parentCode)}, ${q(a.parentLabel)}, ${q(a.normal)}, ${a.isHeader}, ${a.canPost}, ${a.isActive}, ${a.isLocked}, ${a.txCount}, ${q(a.updatedAt)})`
);

const sql = `-- AUTO-GENERATED by scripts/generate-seed-sql.mjs — do not edit by hand.
-- Seeds the coa_accounts table with the Dentico dummy dataset
-- (${seed.length} accounts: ${seed.filter((a) => a.isHeader).length} headers + ${seed.filter((a) => !a.isHeader).length} posting accounts).

insert into public.coa_accounts
  (code, name, type_label, group_code, parent_code, parent_label, normal, is_header, can_post, is_active, is_locked, tx_count, updated_at)
values
${rows.join(",\n")}
on conflict (code) do update set
  name         = excluded.name,
  type_label   = excluded.type_label,
  group_code   = excluded.group_code,
  parent_code  = excluded.parent_code,
  parent_label = excluded.parent_label,
  normal       = excluded.normal,
  is_header    = excluded.is_header,
  can_post     = excluded.can_post,
  is_active    = excluded.is_active,
  is_locked    = excluded.is_locked,
  tx_count     = excluded.tx_count,
  updated_at   = excluded.updated_at;
`;

fs.mkdirSync("supabase", { recursive: true });
fs.writeFileSync("supabase/seed.sql", sql);
console.log(`✔ supabase/seed.sql written (${seed.length} rows)`);
